    final message = _catalogue[locale]?[key] ?? _catalogue[AppLocaleOption.en]![key] ?? key;
    if (values == null) return message;

    var output = message;
    values.forEach((name, value) {
      output = output.replaceAll('{$name}', '$value');
    });
    return output;
